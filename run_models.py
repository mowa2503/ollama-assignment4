#!/usr/bin/env python3
"""Assignment 4: Run the same prompts on two local Ollama models.

Requires: an Ollama server on localhost, both pulled models, and `pip install ollama`.
Writes real model responses and measurements to model_outputs.csv; never fabricates results.
"""

from __future__ import annotations

import argparse
import csv
import sys
import time
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

try:
    from ollama import Client
except ImportError:
    print(
        "The Ollama Python library is not installed. Run: "
        "python -m pip install -r requirements.txt",
        file=sys.stderr,
    )
    raise SystemExit(1)

PROJECT_DIR = Path(__file__).resolve().parent
DEFAULT_MODELS = ("llama3.2:1b", "qwen2.5:1.5b")
PROMPTS = (
    (
        "ai_vs_ml",
        "Explain the difference between artificial intelligence (AI) and "
        "machine learning (ML) to a 14-year-old in exactly three sentences. "
        "Include one everyday example.",
    ),
    (
        "arithmetic",
        "A student has 3 packs with 4 pencils in each pack. "
        "The student gives away 5 pencils. How many pencils remain? "
        "Show the calculation and answer clearly in one or two sentences.",
    ),
)
FIELDS = (
    "timestamp_utc",
    "prompt_id",
    "model",
    "prompt",
    "response",
    "wall_time_seconds",
    "ollama_total_seconds",
    "output_tokens",
)
RESULTS_START = "<!-- AUTO-RESULTS-START -->"
RESULTS_END = "<!-- AUTO-RESULTS-END -->"


def measured_seconds(nanoseconds: Any) -> str:
    """Return Ollama's nanoseconds as seconds, if reported by the API."""
    if nanoseconds is None:
        return ""
    return f"{float(nanoseconds) / 1_000_000_000:.2f}"


def markdown_summary(records: list[dict[str, str]]) -> str:
    """Summarize measurements ONLY; subjective judgments remain for the student."""
    lines = [
        "The following numbers were generated by running `python run_models.py` "
        "on the local machine. They are measured outputs, not sample data.",
        "",
        "| Test | Model | Wall time (seconds) | Ollama total (seconds) | Output tokens |",
        "|---|---|---:|---:|---:|",
    ]
    for row in records:
        lines.append(
            f"| `{row['prompt_id']}` | `{row['model']}` | "
            f"{row['wall_time_seconds']} | {row['ollama_total_seconds'] or 'N/A'} | "
            f"{row['output_tokens'] or 'N/A'} |"
        )

    lines.extend(
        [
            "",
            "These wall-clock times include any model loading and are **not** a "
            "rigorous speed benchmark; they can change between runs.",
            "Open `model_outputs.csv` to inspect the full text of every answer.",
            "",
        ]
    )
    return "\n".join(lines)


def update_readme(records: list[dict[str, str]]) -> None:
    """Insert real measured values into one clearly delimited README section."""
    readme_path = PROJECT_DIR / "README.md"
    readme = readme_path.read_text(encoding="utf-8")
    if readme.count(RESULTS_START) != 1 or readme.count(RESULTS_END) != 1:
        raise ValueError("README result markers missing or duplicated.")
    left, remaining = readme.split(RESULTS_START, maxsplit=1)
    _, right = remaining.split(RESULTS_END, maxsplit=1)
    new_text = (
        left + RESULTS_START + "\n\n" + markdown_summary(records)
        + "\n" + RESULTS_END + right
    )
    readme_path.write_text(new_text, encoding="utf-8")


def run(models: list[str], destination: Path) -> int:
    client = Client(host="http://127.0.0.1:11434", timeout=240.0)

    try:
        client.list()  # Check the server BEFORE creating an output file.
    except Exception as exc:
        print("ERROR: Cannot connect to Ollama on this Mac.", file=sys.stderr)
        print("Open the Ollama app (Applications > Ollama) and try again.", file=sys.stderr)
        print(f"Technical detail: {exc}", file=sys.stderr)
        return 1

    records: list[dict[str, str]] = []
    destination.parent.mkdir(parents=True, exist_ok=True)

    # A complete successful run produces one response for every (prompt, model).
    # Each successful result is written immediately so partial work is not lost.
    with destination.open("w", newline="", encoding="utf-8-sig") as file:
        writer = csv.DictWriter(file, fieldnames=FIELDS)
        writer.writeheader()
        for prompt_id, prompt in PROMPTS:
            for model in models:
                print(f"\nRunning {model} on {prompt_id} ...", flush=True)
                start = time.perf_counter()
                try:
                    result = client.chat(
                        model=model,
                        messages=[{"role": "user", "content": prompt}],
                        stream=False,
                        options={"temperature": 0, "num_predict": 180},
                    )
                except Exception as exc:
                    print(f"ERROR calling {model}: {exc}", file=sys.stderr)
                    print(
                        f"Check 'ollama list'; if needed, run: ollama pull {model}",
                        file=sys.stderr,
                    )
                    print(
                        "Some rows may already be present in the CSV. "
                        "Do not submit until a full run succeeds.",
                        file=sys.stderr,
                    )
                    return 1

                elapsed = time.perf_counter() - start
                answer = (result.message.content or "").strip()
                record = {
                    "timestamp_utc": datetime.now(timezone.utc).isoformat(timespec="seconds"),
                    "prompt_id": prompt_id,
                    "model": model,
                    "prompt": prompt,
                    "response": answer,
                    "wall_time_seconds": f"{elapsed:.2f}",
                    "ollama_total_seconds": measured_seconds(
                        getattr(result, "total_duration", None)
                    ),
                    "output_tokens": str(getattr(result, "eval_count", None) or ""),
                }
                writer.writerow(record)
                file.flush()
                records.append(record)
                print(f"Done in {elapsed:.2f} seconds.")
                print("Response preview: " + answer[:220].replace("\n", " "))

    try:
        update_readme(records)
    except (OSError, ValueError) as exc:
        print(f"WARNING: Could not update README: {exc}", file=sys.stderr)
        print("The CSV was saved. Add the observations to README manually.")

    print(f"\nSUCCESS: {len(records)} real model responses saved to:\n{destination}")
    print("Please review the CSV and complete the personal observations in README.md")
    print("before uploading the project to GitHub.")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--output", type=Path, default=PROJECT_DIR / "model_outputs.csv",
        help="CSV output path (default: model_outputs.csv in this project)",
    )
    parser.add_argument(
        "--models", nargs="+", default=list(DEFAULT_MODELS),
        help="Two or more previously pulled Ollama models",
    )
    args = parser.parse_args()
    if len(set(args.models)) < 2:
        parser.error("At least two distinct model names are required.")
    return run(args.models, args.output.expanduser().resolve())


if __name__ == "__main__":
    raise SystemExit(main())
